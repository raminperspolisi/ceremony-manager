const normalizeSearchText = (value) => String(value ?? '')
  .toLocaleLowerCase('fa-IR')
  .replace(/[يى]/g, 'ی')
  .replace(/ك/g, 'ک')
  .replace(/\s+/g, ' ')
  .trim();

export default function TutorialPanel() {
  const [search, setSearch] = useState('');
  const [openSections, setOpenSections] = useState(() => new Set([sections[0].id]));
  const filteredSections = useMemo(() => {
    const query = normalizeSearchText(search);
    if (!query) return sections;
    return sections.filter((section) => normalizeSearchText([
      section.title,
      section.summary,
      ...section.steps,
      section.note,
    ].join(' ')).includes(query));
  }, [search]);

  const toggleSection = (sectionId) => {
    setOpenSections((currentSections) => {
      const nextSections = new Set(currentSections);
      if (nextSections.has(sectionId)) nextSections.delete(sectionId);
      else nextSections.add(sectionId);
      return nextSections;
    });
  };

  const setAllSectionsOpen = (isOpen) => {
    setOpenSections(isOpen ? new Set(filteredSections.map((section) => section.id)) : new Set());
  };

  return (
    <article className="tutorial-panel" dir="rtl">
      <header className="tutorial-header">
        <div>
          <p className="tutorial-eyebrow">راهنمای گام‌به‌گام</p>
          <h2>آموزش استفاده از نرم‌افزار</h2>
          <p>برای شروع یک موضوع را باز کنید یا در راهنما جست‌وجو کنید. بعضی بخش‌ها فقط با مجوز مدیر فضای کاری در دسترس‌اند.</p>
        </div>
        <div className="tutorial-header-mark" aria-hidden="true">؟</div>
      </header>

      <div className="tutorial-toolbar">
        <label className="tutorial-search">
          <span aria-hidden="true">⌕</span>
          <span className="sr-only">جست‌وجو در آموزش</span>
          <input
            type="search"
            value={search}
            onChange={(event) => setSearch(event.target.value)}
            placeholder="جست‌وجو؛ مثلاً تسویه، رزرو یا پشتیبان‌گیری"
          />
          {search && (
            <button type="button" onClick={() => setSearch('')} aria-label="پاک‌کردن جست‌وجو">×</button>
          )}
        </label>
        <div className="tutorial-toolbar-actions">
          <button type="button" onClick={() => setAllSectionsOpen(true)}>بازکردن همه</button>
          <button type="button" onClick={() => setAllSectionsOpen(false)}>بستن همه</button>
        </div>
      </div>

      <p className="tutorial-result-count" aria-live="polite">
        {filteredSections.length
          ? `${filteredSections.length.toLocaleString('fa-IR')} موضوع آموزشی`
          : 'موضوعی با این عبارت پیدا نشد.'}
      </p>

      <div className="tutorial-sections">
        {filteredSections.map((section, index) => {
          const isOpen = openSections.has(section.id);
          const panelId = `tutorial-content-${section.id}`;
          return (
            <section className={`tutorial-section${isOpen ? ' is-open' : ''}`} key={section.id}>
              <h3>
                <button
                  type="button"
                  className="tutorial-section-toggle"
                  aria-expanded={isOpen}
                  aria-controls={panelId}
                  onClick={() => toggleSection(section.id)}
                >
                  <span className="tutorial-section-number">{(index + 1).toLocaleString('fa-IR')}</span>
                  <span className="tutorial-section-heading">
                    <strong>{section.title}</strong>
                    <small>{section.summary}</small>
                  </span>
                  <span className="tutorial-section-chevron" aria-hidden="true">{isOpen ? '−' : '+'}</span>
                </button>
              </h3>
              <div className="tutorial-section-content" id={panelId} hidden={!isOpen}>
                <ol>
                  {section.steps.map((step) => <li key={step}>{step}</li>)}
                </ol>
                {section.note && <p className="tutorial-note"><strong>نکته:</strong> {section.note}</p>}
              </div>
            </section>
          );
        })}
      </div>
      <footer className="tutorial-footer">
        راهنما بر اساس امکانات فعال برنامه نوشته شده است. در صورت تفاوت گزینه‌ها، نسخهٔ برنامه و دسترسی فضای کاری را بررسی کنید.
      </footer>
    </article>
  );
}
