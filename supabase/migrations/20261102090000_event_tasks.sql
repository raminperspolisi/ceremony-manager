CREATE TABLE IF NOT EXISTS public.event_tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id uuid NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 180),
  assignee text CHECK (assignee IS NULL OR length(assignee) <= 120),
  completed boolean NOT NULL DEFAULT false,
  offline_sync_id uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS event_tasks_offline_sync_id_key
  ON public.event_tasks (offline_sync_id);
CREATE INDEX IF NOT EXISTS event_tasks_organization_event_created_idx
  ON public.event_tasks (organization_id, event_id, created_at);

ALTER TABLE public.event_tasks ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.event_tasks FROM anon, PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.event_tasks TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.event_tasks_id_seq TO authenticated;

DROP POLICY IF EXISTS event_tasks_calendar_access ON public.event_tasks;
CREATE POLICY event_tasks_calendar_access
ON public.event_tasks
FOR ALL
TO authenticated
USING (
  public.is_organization_member(organization_id)
  AND public.has_organization_section(organization_id, 'calendar')
  AND EXISTS (
    SELECT 1
    FROM public.events
    WHERE events.id = event_tasks.event_id
      AND events.organization_id = event_tasks.organization_id
  )
)
WITH CHECK (
  public.is_organization_member(organization_id)
  AND public.has_organization_section(organization_id, 'calendar')
  AND EXISTS (
    SELECT 1
    FROM public.events
    WHERE events.id = event_tasks.event_id
      AND events.organization_id = event_tasks.organization_id
  )
);

DROP TRIGGER IF EXISTS prevent_organization_change ON public.event_tasks;
CREATE TRIGGER prevent_organization_change
BEFORE UPDATE ON public.event_tasks
FOR EACH ROW
EXECUTE FUNCTION public.prevent_organization_change();

