CREATE OR REPLACE FUNCTION public.set_organization_member_role(
  p_organization_id uuid,
  p_user_id uuid,
  p_role text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM public.organization_memberships AS membership
    WHERE membership.organization_id = p_organization_id
      AND membership.user_id = (SELECT auth.uid())
      AND membership.role = 'owner'
  ) THEN
    RAISE EXCEPTION 'Only the organization owner can change administrator roles.';
  END IF;
  IF p_role IS NULL
    OR p_role NOT IN ('admin', 'member')
    OR p_user_id = (SELECT auth.uid()) THEN
