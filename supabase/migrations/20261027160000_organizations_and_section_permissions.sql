CREATE OR REPLACE FUNCTION public.update_member_section_permissions(
  p_organization_id uuid,
  p_user_id uuid,
  p_section_permissions jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_supported_sections text[] := ARRAY[
    'dashboard', 'customers', 'inventory', 'quotations', 'official',
    'bot_orders', 'backup', 'accounting', 'calendar', 'tutorial', 'contact'
  ];
BEGIN
  IF NOT public.is_organization_admin(p_organization_id) THEN
    RAISE EXCEPTION 'Organization administrator access is required.';
  END IF;
  IF jsonb_typeof(p_section_permissions) IS DISTINCT FROM 'object' THEN
    RAISE EXCEPTION 'Section permissions must be a JSON object.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM jsonb_each(p_section_permissions) AS permission(key, value)
    WHERE NOT (permission.key = ANY(v_supported_sections))
       OR jsonb_typeof(permission.value) IS DISTINCT FROM 'boolean'
  ) THEN
    RAISE EXCEPTION 'Section permissions contain an unsupported value.';
  END IF;

  UPDATE public.organization_memberships
  SET section_permissions = p_section_permissions
  WHERE organization_id = p_organization_id
    AND user_id = p_user_id
    AND role = 'member';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'The target organization member was not found or cannot be changed.';
  END IF;
END;
$function$;

