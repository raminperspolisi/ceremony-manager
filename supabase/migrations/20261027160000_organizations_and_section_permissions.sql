CREATE OR REPLACE FUNCTION public.set_cash_transaction_organization()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_organization_id uuid;
BEGIN
  SELECT account.organization_id
  INTO v_organization_id
  FROM public.financial_accounts AS account
  WHERE account.id = NEW.account_id;

  IF v_organization_id IS NULL THEN
    RAISE EXCEPTION 'The source account does not exist.';
  END IF;
  IF NEW.organization_id IS NOT NULL AND NEW.organization_id <> v_organization_id THEN
    RAISE EXCEPTION 'The transaction organization must match its source account.';
  END IF;

  IF NEW.transfer_to_account_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.financial_accounts AS account
    WHERE account.id = NEW.transfer_to_account_id
      AND account.organization_id = v_organization_id
  ) THEN
    RAISE EXCEPTION 'The destination account belongs to another organization.';
  END IF;

  IF NEW.invoice_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.invoices AS invoice
    WHERE invoice.id = NEW.invoice_id
      AND invoice.organization_id = v_organization_id
  ) THEN
    RAISE EXCEPTION 'The invoice belongs to another organization.';
  END IF;

  NEW.organization_id := v_organization_id;
  RETURN NEW;
END;
$function$;

