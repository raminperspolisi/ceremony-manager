CREATE TABLE IF NOT EXISTS public.cash_transaction_edit_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
  cash_transaction_id bigint NOT NULL REFERENCES public.cash_transactions(id) ON DELETE RESTRICT,
  edited_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  reason text NOT NULL CHECK (length(btrim(reason)) BETWEEN 4 AND 240),
  before_data jsonb NOT NULL,
  after_data jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS cash_transaction_edit_history_transaction_idx
  ON public.cash_transaction_edit_history (cash_transaction_id, created_at DESC);

ALTER TABLE public.cash_transaction_edit_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.cash_transaction_edit_history FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.edit_cash_transaction(
  p_transaction_id bigint,
  p_transaction jsonb,
  p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_original public.cash_transactions%ROWTYPE;
  v_parent public.cash_transactions%ROWTYPE;
  v_invoice public.invoices%ROWTYPE;
  v_expense public.invoice_expenses%ROWTYPE;
  v_account public.financial_accounts%ROWTYPE;
  v_type text := p_transaction->>'transaction_type';
  v_amount numeric(14, 0) := (p_transaction->>'amount')::numeric;
  v_account_id bigint := NULLIF(p_transaction->>'account_id', '')::bigint;
  v_destination_id bigint := NULLIF(p_transaction->>'transfer_to_account_id', '')::bigint;
  v_event_id uuid := NULLIF(p_transaction->>'event_id', '')::uuid;
  v_date date := (p_transaction->>'transaction_date')::date;
  v_category text := NULLIF(btrim(p_transaction->>'category'), '');
  v_description text := COALESCE(p_transaction->>'description', '');
  v_reference_number text := NULLIF(btrim(p_transaction->>'reference_number'), '');
  v_receipt_note text := NULLIF(btrim(p_transaction->>'receipt_note'), '');
  v_reason text := btrim(COALESCE(p_reason, ''));
  v_invoice_id bigint;
  v_invoice_delta numeric(14, 0) := 0;
  v_expected_type text;
  v_new_paid numeric(14, 0);
  v_balance numeric(14, 0);
  v_old_balance numeric(14, 0);
  v_before jsonb;
  v_after jsonb;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'برای اصلاح گردش باید وارد حساب شوید.';
  END IF;
  IF p_transaction_id IS NULL OR length(v_reason) NOT BETWEEN 4 AND 240 THEN
    RAISE EXCEPTION 'گردش و دلیل اصلاح (۴ تا ۲۴۰ نویسه) الزامی است.';
  END IF;
  IF v_type NOT IN ('income', 'expense', 'transfer')
    OR v_amount IS NULL OR v_amount <= 0
    OR v_account_id IS NULL OR v_date IS NULL THEN
    RAISE EXCEPTION 'نوع، مبلغ، حساب و تاریخ گردش معتبر نیست.';
  END IF;
  IF length(v_description) > 240
    OR length(v_reference_number) > 80
    OR length(v_receipt_note) > 240 THEN
    RAISE EXCEPTION 'توضیحات یا اطلاعات رسید بیش از حد مجاز است.';
  END IF;
  IF v_type = 'transfer'
    AND (v_destination_id IS NULL OR v_destination_id = v_account_id OR v_event_id IS NOT NULL) THEN
    RAISE EXCEPTION 'حساب مقصد انتقال معتبر نیست و انتقال به مراسم متصل نمی‌شود.';
  END IF;
  IF v_type <> 'transfer' AND v_destination_id IS NOT NULL THEN
    RAISE EXCEPTION 'حساب مقصد فقط برای انتقال قابل استفاده است.';
  END IF;
  IF v_type = 'expense' AND v_category IS NULL THEN
    RAISE EXCEPTION 'دسته‌بندی هزینه الزامی است.';
  END IF;

  SELECT * INTO v_original
  FROM public.cash_transactions
  WHERE id = p_transaction_id
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'گردش موردنظر پیدا نشد.'; END IF;
  IF NOT public.is_organization_member(v_original.organization_id)
    OR NOT public.has_organization_section(v_original.organization_id, 'accounting') THEN
    RAISE EXCEPTION 'برای اصلاح گردش به دسترسی حسابداری نیاز دارید.';
  END IF;

  IF v_original.reversal_of_transaction_id IS NOT NULL THEN
    SELECT * INTO v_parent
    FROM public.cash_transactions
    WHERE id = v_original.reversal_of_transaction_id
    FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'گردش اصلیِ برگشت پیدا نشد.'; END IF;
    v_expected_type := CASE v_parent.transaction_type
      WHEN 'income' THEN 'expense'
      WHEN 'expense' THEN 'income'
      ELSE 'transfer'
    END;
    IF v_type IS DISTINCT FROM v_expected_type THEN
      RAISE EXCEPTION 'نوع گردش برگشتی باید با گردش اصلی سازگار بماند.';
    END IF;
    v_invoice_id := v_parent.invoice_id;
    v_invoice_delta := v_original.amount - v_amount;
  ELSE
    v_invoice_id := v_original.invoice_id;
    IF EXISTS (
      SELECT 1
      FROM public.cash_transactions AS reversal
      WHERE reversal.reversal_of_transaction_id = v_original.id
    ) AND v_type IS DISTINCT FROM v_original.transaction_type THEN
      RAISE EXCEPTION 'نوع گردش برگشت‌خورده قابل تغییر نیست.';
    END IF;
    IF v_invoice_id IS NOT NULL THEN
      IF v_type <> 'income' OR v_event_id IS NOT NULL THEN
        RAISE EXCEPTION 'نوع دریافت فاکتور و اتصال مراسم آن قابل تغییر نیست.';
      END IF;
      v_invoice_delta := v_amount - v_original.amount;
    END IF;
  END IF;

  SELECT * INTO v_expense
  FROM public.invoice_expenses
  WHERE cash_transaction_id = v_original.id
  FOR UPDATE;
  IF FOUND AND v_type <> 'expense' THEN
    RAISE EXCEPTION 'نوع پرداخت هزینهٔ فاکتور باید هزینه باقی بماند.';
  END IF;
  IF v_original.reversal_of_transaction_id IS NOT NULL
    AND v_type = 'transfer'
    AND (v_account_id <> v_parent.transfer_to_account_id
      OR v_destination_id <> v_parent.account_id) THEN
    RAISE EXCEPTION 'حساب‌های گردش برگشتی باید با جهت انتقال اصلی سازگار بمانند.';
  END IF;

  IF v_invoice_id IS NOT NULL THEN
    SELECT * INTO v_invoice
    FROM public.invoices
    WHERE id = v_invoice_id
    FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'فاکتور مرتبط با گردش پیدا نشد.'; END IF;
    v_new_paid := COALESCE(v_invoice.paid_amount, 0) + v_invoice_delta;
    IF v_new_paid < 0 OR v_new_paid > COALESCE(v_invoice.total_price, 0) THEN
      RAISE EXCEPTION 'مبلغ اصلاح‌شده با ماندهٔ فاکتور سازگار نیست.';
    END IF;
  END IF;

  PERFORM account.id
  FROM public.financial_accounts AS account
  WHERE account.organization_id = v_original.organization_id
    AND account.id IN (
      v_original.account_id,
      v_original.transfer_to_account_id,
      v_account_id,
      v_destination_id
    )
  ORDER BY account.id
  FOR UPDATE;

  SELECT * INTO v_account
  FROM public.financial_accounts
  WHERE id = v_account_id
    AND organization_id = v_original.organization_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'حساب انتخاب‌شده معتبر نیست.'; END IF;
  IF v_date < v_account.opening_date THEN
    RAISE EXCEPTION 'تاریخ گردش نمی‌تواند قبل از تاریخ افتتاح حساب باشد.';
  END IF;
  IF v_destination_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.financial_accounts AS destination
    WHERE destination.id = v_destination_id
      AND destination.organization_id = v_original.organization_id
  ) THEN
    RAISE EXCEPTION 'حساب مقصد معتبر نیست.';
  END IF;

  FOR v_account IN
    SELECT account.*
    FROM public.financial_accounts AS account
    WHERE account.organization_id = v_original.organization_id
      AND account.id IN (
        v_original.account_id,
        v_original.transfer_to_account_id,
        v_account_id,
        v_destination_id
      )
    ORDER BY account.id
  LOOP
    SELECT account.opening_balance
      + COALESCE(SUM(CASE
          WHEN transaction.transaction_type = 'income' THEN transaction.amount
          WHEN transaction.transaction_type IN ('expense', 'transfer') THEN -transaction.amount
          ELSE 0
        END), 0)
      + COALESCE((
          SELECT SUM(incoming.amount)
          FROM public.cash_transactions AS incoming
          WHERE incoming.transaction_type = 'transfer'
            AND incoming.transfer_to_account_id = account.id
            AND incoming.organization_id = v_original.organization_id
        ), 0)
    INTO v_old_balance
    FROM public.financial_accounts AS account
    LEFT JOIN public.cash_transactions AS transaction
      ON transaction.account_id = account.id
      AND transaction.organization_id = v_original.organization_id
    WHERE account.id = v_account.id
    GROUP BY account.id, account.opening_balance;

    SELECT account.opening_balance
      + COALESCE(SUM(CASE
          WHEN transaction.transaction_type = 'income' THEN transaction.amount
          WHEN transaction.transaction_type IN ('expense', 'transfer') THEN -transaction.amount
          ELSE 0
        END), 0)
      + COALESCE((
          SELECT SUM(incoming.amount)
          FROM public.cash_transactions AS incoming
          WHERE incoming.transaction_type = 'transfer'
            AND incoming.transfer_to_account_id = account.id
            AND incoming.organization_id = v_original.organization_id
            AND incoming.id <> v_original.id
        ), 0)
    INTO v_balance
    FROM public.financial_accounts AS account
    LEFT JOIN public.cash_transactions AS transaction
      ON transaction.account_id = account.id
      AND transaction.organization_id = v_original.organization_id
      AND transaction.id <> v_original.id
    WHERE account.id = v_account.id
    GROUP BY account.id, account.opening_balance;

    IF v_account.id = v_account_id THEN
      v_balance := v_balance + CASE v_type
        WHEN 'income' THEN v_amount
        WHEN 'expense' THEN -v_amount
        ELSE -v_amount
      END;
    END IF;
    IF v_type = 'transfer' AND v_account.id = v_destination_id THEN
      v_balance := v_balance + v_amount;
    END IF;
    IF v_balance < 0 AND v_balance < v_old_balance THEN
      RAISE EXCEPTION 'این اصلاح باعث منفی‌شدن موجودی حساب می‌شود.';
    END IF;
  END LOOP;

  v_before := to_jsonb(v_original);
  UPDATE public.cash_transactions
  SET transaction_type = v_type,
      amount = v_amount,
      account_id = v_account_id,
      transfer_to_account_id = v_destination_id,
      event_id = v_event_id,
      category = v_category,
      description = v_description,
      transaction_date = v_date,
      reference_number = v_reference_number,
      receipt_note = v_receipt_note
  WHERE id = v_original.id
  RETURNING * INTO v_original;
  v_after := to_jsonb(v_original);

  INSERT INTO public.cash_transaction_edit_history (
    organization_id, cash_transaction_id, edited_by, reason, before_data, after_data
  ) VALUES (
    v_original.organization_id, v_original.id, auth.uid(), v_reason, v_before, v_after
  );

  IF v_invoice_id IS NOT NULL AND v_invoice_delta <> 0 THEN
    UPDATE public.invoices
    SET paid_amount = v_new_paid,
        payment_status = CASE
          WHEN v_new_paid <= 0 THEN 'unpaid'
          WHEN COALESCE(total_price, 0) > 0 AND v_new_paid >= total_price THEN 'paid'
          ELSE 'deposit_paid'
        END
    WHERE id = v_invoice_id
    RETURNING * INTO v_invoice;
  END IF;

  IF v_expense.id IS NOT NULL THEN
    UPDATE public.invoice_expenses
    SET amount = v_amount,
        category = v_category,
        expense_date = v_date,
        payment_date = v_date,
        account_id = v_account_id
    WHERE id = v_expense.id
    RETURNING * INTO v_expense;
  END IF;

  RETURN jsonb_build_object(
    'transaction', to_jsonb(v_original),
    'invoice', CASE WHEN v_invoice.id IS NULL THEN NULL ELSE to_jsonb(v_invoice) END,
    'invoice_expense', CASE WHEN v_expense.id IS NULL THEN NULL ELSE to_jsonb(v_expense) END
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.edit_cash_transaction(bigint, jsonb, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.edit_cash_transaction(bigint, jsonb, text) TO authenticated;
