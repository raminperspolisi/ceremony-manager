CREATE TABLE public.bot_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telegram_user_id text NOT NULL,
  customer_name text NOT NULL,
  telegram_username text NOT NULL DEFAULT '',
  items jsonb NOT NULL CHECK (jsonb_typeof(items) = 'array'),
  total_price numeric(14, 0) CHECK (total_price IS NULL OR total_price >= 0),
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'completed', 'cancelled')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX bot_orders_created_at_idx
  ON public.bot_orders (created_at DESC, id DESC);
CREATE INDEX bot_orders_status_created_at_idx
  ON public.bot_orders (status, created_at DESC);

ALTER TABLE public.bot_orders ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.bot_orders FROM anon, PUBLIC;
GRANT SELECT ON TABLE public.bot_orders TO authenticated;
GRANT UPDATE (status, total_price) ON TABLE public.bot_orders TO authenticated;

DROP POLICY IF EXISTS "Authenticated users can read bot orders"
  ON public.bot_orders;
CREATE POLICY "Authenticated users can read bot orders"
ON public.bot_orders
FOR SELECT
TO authenticated
USING (true);

DROP POLICY IF EXISTS "Authenticated users can update bot order status"
  ON public.bot_orders;
CREATE POLICY "Authenticated users can update bot order status"
ON public.bot_orders
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (status IN ('pending', 'processing', 'completed', 'cancelled'));

CREATE OR REPLACE FUNCTION public.submit_bot_order(
  p_telegram_user_id text,
  p_customer_name text,
  p_telegram_username text,
  p_items jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_item jsonb;
  v_product record;
  v_quantity numeric;
  v_total numeric(14, 0) := 0;
  v_has_unpriced_item boolean := false;
  v_order_items jsonb := '[]'::jsonb;
  v_order_id bigint;
BEGIN
  IF NULLIF(btrim(p_telegram_user_id), '') IS NULL
    OR NULLIF(btrim(p_customer_name), '') IS NULL THEN
    RAISE EXCEPTION 'شناسهٔ مشتری و نام نمایشی الزامی است.';
  END IF;
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'فهرست اقلام سفارش معتبر نیست.';
  END IF;
  IF jsonb_array_length(p_items) < 1 OR jsonb_array_length(p_items) > 50 THEN
    RAISE EXCEPTION 'فهرست اقلام سفارش معتبر نیست.';
  END IF;

  FOR v_item IN
    SELECT entry.value
    FROM jsonb_array_elements(p_items) AS entry(value)
  LOOP
    IF jsonb_typeof(v_item) IS DISTINCT FROM 'object'
      OR NULLIF(v_item->>'id', '') IS NULL
      OR jsonb_typeof(v_item->'quantity') IS DISTINCT FROM 'number' THEN
      RAISE EXCEPTION 'قلم سفارش معتبر نیست.';
    END IF;

    v_quantity := (v_item->>'quantity')::numeric;
    IF v_quantity <> trunc(v_quantity) OR v_quantity < 1 OR v_quantity > 99 THEN
      RAISE EXCEPTION 'تعداد هر قلم باید بین ۱ تا ۹۹ باشد.';
    END IF;
    IF EXISTS (
      SELECT 1
      FROM jsonb_array_elements(v_order_items) AS saved(value)
      WHERE saved.value->>'id' = v_item->>'id'
    ) THEN
      RAISE EXCEPTION 'یک کالا در سفارش تکراری است.';
    END IF;

    SELECT inventory.id,
           inventory.title,
           COALESCE(inventory.item_type, 'sale') AS item_type,
           catalog.public_price,
           catalog.description
    INTO v_product
    FROM public.bot_catalog_items AS catalog
    JOIN public.inventory AS inventory
      ON inventory.id = catalog.inventory_id
    WHERE inventory.id::text = v_item->>'id';

    IF NOT FOUND THEN
      RAISE EXCEPTION 'یکی از کالاهای انتخاب‌شده دیگر در کاتالوگ نیست.';
    END IF;

    v_order_items := v_order_items || jsonb_build_array(jsonb_build_object(
      'id', v_product.id::text,
      'title', v_product.title,
      'item_type', v_product.item_type,
      'quantity', v_quantity,
      'unit_price', v_product.public_price,
      'description', v_product.description
    ));

    IF v_product.public_price IS NULL THEN
      v_has_unpriced_item := true;
    ELSE
      v_total := v_total + (v_product.public_price * v_quantity);
    END IF;
  END LOOP;

  INSERT INTO public.bot_orders (
    telegram_user_id,
    customer_name,
    telegram_username,
    items,
    total_price
  )
  VALUES (
    btrim(p_telegram_user_id),
    left(btrim(p_customer_name), 120),
    left(COALESCE(btrim(p_telegram_username), ''), 64),
    v_order_items,
    CASE WHEN v_has_unpriced_item THEN NULL ELSE v_total END
  )
  RETURNING id INTO v_order_id;

  RETURN jsonb_build_object('id', v_order_id);
END;
$function$;

REVOKE ALL ON FUNCTION public.submit_bot_order(text, text, text, jsonb)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.submit_bot_order(text, text, text, jsonb)
  TO anon;
