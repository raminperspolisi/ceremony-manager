CREATE OR REPLACE FUNCTION public.validate_inventory_reservation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $function$
DECLARE
  v_item_type text;
  v_stock numeric(14, 3);
  v_reserved numeric(14, 3);
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.offline_sync_id = OLD.offline_sync_id
      AND (to_jsonb(NEW) - 'id' - 'created_at' - 'status')
        IS NOT DISTINCT FROM (to_jsonb(OLD) - 'id' - 'created_at' - 'status') THEN
      IF OLD.status = 'reserved' AND NEW.status = 'cancelled' THEN
        RETURN NEW;
      END IF;
      IF OLD.status = NEW.status THEN
        RETURN OLD;
      END IF;
      IF NEW.status = 'reserved'
        AND OLD.status IN ('issued', 'fulfilled', 'returned', 'cancelled') THEN
        RETURN OLD;
      END IF;
      IF OLD.status = 'reserved' AND NEW.status IN ('issued', 'fulfilled')
        AND EXISTS (
          SELECT 1
          FROM public.inventory_stock_movements AS movement
          WHERE movement.reservation_id = OLD.id
            AND movement.quantity_delta = -OLD.quantity
            AND (
              (NEW.status = 'issued' AND movement.movement_type = 'rental_issue')
              OR (NEW.status = 'fulfilled' AND movement.movement_type = 'sale_issue')
            )
        ) THEN
        RETURN NEW;
      END IF;
      IF OLD.status = 'issued' AND NEW.status = 'returned'
        AND EXISTS (
          SELECT 1
          FROM public.inventory_stock_movements AS movement
          WHERE movement.reservation_id = OLD.id
            AND movement.movement_type = 'rental_return'
            AND movement.quantity_delta = OLD.quantity
        ) THEN
        RETURN NEW;
      END IF;
    END IF;
    RAISE EXCEPTION 'رزرو فقط از مسیر مجاز انبار قابل تغییر است.';
  END IF;

  SELECT COALESCE(item.item_type, 'sale')
  INTO v_item_type
  FROM public.inventory AS item
  JOIN public.inventory_warehouses AS warehouse
    ON warehouse.organization_id = item.organization_id
  WHERE item.id = NEW.inventory_id
    AND item.organization_id = NEW.organization_id
    AND warehouse.id = NEW.warehouse_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'کالا یا انبار متعلق به فضای کاری فعال نیست.';
  END IF;
  IF (NEW.reservation_type = 'rent' AND v_item_type <> 'rent')
    OR (NEW.reservation_type = 'sale' AND v_item_type <> 'sale') THEN
    RAISE EXCEPTION 'نوع رزرو با نوع کالا هم‌خوانی ندارد.';
  END IF;

  PERFORM 1 FROM public.inventory AS item
  WHERE item.id = NEW.inventory_id AND item.organization_id = NEW.organization_id
  FOR UPDATE;
  SELECT COALESCE(sum(movement.quantity_delta), 0)
  INTO v_stock
  FROM public.inventory_stock_movements AS movement
  WHERE movement.organization_id = NEW.organization_id
    AND movement.inventory_id = NEW.inventory_id
    AND movement.warehouse_id = NEW.warehouse_id;

  IF NEW.reservation_type = 'rent' THEN
    SELECT COALESCE(sum(reservation.quantity), 0)
    INTO v_reserved
    FROM public.inventory_reservations AS reservation
    WHERE reservation.organization_id = NEW.organization_id
      AND reservation.inventory_id = NEW.inventory_id
      AND reservation.warehouse_id = NEW.warehouse_id
      AND reservation.status = 'reserved'
      AND reservation.reservation_type = 'rent'
      AND reservation.starts_on <= NEW.ends_on
      AND reservation.ends_on >= NEW.starts_on;
  ELSE
    SELECT COALESCE(sum(reservation.quantity), 0)
    INTO v_reserved
    FROM public.inventory_reservations AS reservation
    WHERE reservation.organization_id = NEW.organization_id
      AND reservation.inventory_id = NEW.inventory_id
      AND reservation.warehouse_id = NEW.warehouse_id
      AND reservation.status = 'reserved'
      AND reservation.reservation_type = 'sale';
  END IF;

  IF v_stock - v_reserved < NEW.quantity THEN
    RAISE EXCEPTION 'موجودی آزاد برای این رزرو کافی نیست.';
  END IF;
  RETURN NEW;
END;
$function$;

