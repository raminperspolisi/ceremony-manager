CREATE OR REPLACE FUNCTION public.sync_bot_order_inventory_reservations()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_item jsonb;
  v_item_type text;
  v_inventory_id bigint;
  v_quantity numeric(14, 3);
  v_warehouse_id bigint;
BEGIN
  IF NEW.status = 'approved' AND OLD.status IS DISTINCT FROM 'approved' THEN
    IF OLD.status <> 'pending' THEN
      RAISE EXCEPTION 'فقط سفارش در انتظار بررسی قابل تأیید است.';
    END IF;

    SELECT warehouse.id INTO v_warehouse_id
    FROM public.inventory_warehouses AS warehouse
    WHERE warehouse.organization_id = NEW.organization_id
      AND warehouse.is_default
    FOR UPDATE;
    IF v_warehouse_id IS NULL THEN
      RAISE EXCEPTION 'برای این فضای کاری انبار اصلی تعریف نشده است.';
    END IF;

    FOR v_item IN SELECT entry.value FROM jsonb_array_elements(NEW.items) AS entry(value)
    LOOP
      v_inventory_id := NULLIF(v_item->>'id', '')::bigint;
      v_quantity := NULLIF(v_item->>'quantity', '')::numeric;
      SELECT COALESCE(item.item_type, 'sale') INTO v_item_type
      FROM public.inventory AS item
      WHERE item.id = v_inventory_id
        AND item.organization_id = NEW.organization_id
      FOR UPDATE;
      IF NOT FOUND OR v_quantity IS NULL OR v_quantity <= 0 THEN
        RAISE EXCEPTION 'یکی از اقلام سفارش برای رزرو موجودی معتبر نیست.';
      END IF;

      IF v_item_type = 'rent' THEN
        IF NEW.rental_checkout_date IS NULL
          OR NEW.rental_return_date IS NULL
          OR NEW.rental_return_date < NEW.rental_checkout_date THEN
          RAISE EXCEPTION 'برای تأیید سفارش اجاره، تاریخ تحویل و عودت معتبر را ثبت کنید.';
        END IF;
        INSERT INTO public.inventory_reservations (
          organization_id, inventory_id, warehouse_id, source_type, source_id,
          reservation_type, quantity, starts_on, ends_on, note, offline_sync_id
        )
        VALUES (
          NEW.organization_id, v_inventory_id, v_warehouse_id, 'bot', NEW.id::text,
          'rent', v_quantity, NEW.rental_checkout_date, NEW.rental_return_date,
          'رزرو از سفارش ربات', gen_random_uuid()
        );
      ELSE
        INSERT INTO public.inventory_reservations (
          organization_id, inventory_id, warehouse_id, source_type, source_id,
          reservation_type, quantity, note, offline_sync_id
        )
        VALUES (
          NEW.organization_id, v_inventory_id, v_warehouse_id, 'bot', NEW.id::text,
          'sale', v_quantity, 'رزرو از سفارش ربات', gen_random_uuid()
        );
      END IF;
    END LOOP;
  ELSIF NEW.status IN ('rejected', 'cancelled')
    AND OLD.status IS DISTINCT FROM NEW.status THEN
    IF EXISTS (
      SELECT 1 FROM public.inventory_reservations AS reservation
      WHERE reservation.organization_id = NEW.organization_id
        AND reservation.source_type = 'bot'
        AND reservation.source_id = NEW.id::text
        AND reservation.status IN ('issued', 'fulfilled')
    ) THEN
      RAISE EXCEPTION 'پس از تحویل موجودی، لغو سفارش از مسیر انبار انجام می‌شود.';
    END IF;
    UPDATE public.inventory_reservations
    SET status = 'cancelled'
    WHERE organization_id = NEW.organization_id
      AND source_type = 'bot'
      AND source_id = NEW.id::text
      AND status = 'reserved';
  END IF;
  RETURN NEW;
END;
$function$;

