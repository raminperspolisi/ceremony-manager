CREATE OR REPLACE FUNCTION public.validate_inventory_stock_movement()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $function$
DECLARE
  v_stock numeric(14, 3);
  v_reserved numeric(14, 3);
  v_reservation public.inventory_reservations%ROWTYPE;
BEGIN
  IF NEW.movement_type = 'purchase' AND NOT EXISTS (
    SELECT 1
    FROM public.inventory_purchase_receipts AS receipt
    WHERE receipt.id::text = NEW.source_id
      AND receipt.organization_id = NEW.organization_id
      AND receipt.inventory_id = NEW.inventory_id
      AND receipt.warehouse_id = NEW.warehouse_id
      AND receipt.quantity = NEW.quantity_delta
      AND receipt.unit_cost IS NOT DISTINCT FROM NEW.unit_cost
      AND NEW.source_type = 'purchase'
  ) THEN
    RAISE EXCEPTION 'گردش خرید باید از رسید خرید معتبر ایجاد شود.';
  END IF;
  IF NEW.movement_type IN ('transfer_in', 'transfer_out') AND NOT EXISTS (
    SELECT 1
    FROM public.inventory_transfers AS transfer
    WHERE transfer.id::text = NEW.source_id
      AND transfer.organization_id = NEW.organization_id
      AND transfer.inventory_id = NEW.inventory_id
      AND transfer.quantity = abs(NEW.quantity_delta)
      AND NEW.source_type = 'transfer'
      AND (
        (NEW.movement_type = 'transfer_out' AND transfer.from_warehouse_id = NEW.warehouse_id)
        OR (NEW.movement_type = 'transfer_in' AND transfer.to_warehouse_id = NEW.warehouse_id)
      )
  ) THEN
    RAISE EXCEPTION 'گردش انتقال باید از انتقال معتبر بین انبارها ایجاد شود.';
  END IF;

  PERFORM 1
  FROM public.inventory AS item
  WHERE item.id = NEW.inventory_id
    AND item.organization_id = NEW.organization_id
  FOR UPDATE;
  IF NOT FOUND OR NOT EXISTS (
    SELECT 1
    FROM public.inventory_warehouses AS warehouse
    WHERE warehouse.id = NEW.warehouse_id
      AND warehouse.organization_id = NEW.organization_id
  ) THEN
    RAISE EXCEPTION 'کالا یا انبار متعلق به فضای کاری فعال نیست.';
  END IF;

  IF (NEW.movement_type IN ('opening', 'purchase', 'rental_return', 'transfer_in')
      AND NEW.quantity_delta < 0)
    OR (NEW.movement_type IN ('sale_issue', 'rental_issue', 'damage', 'transfer_out')
      AND NEW.quantity_delta > 0) THEN
    RAISE EXCEPTION 'جهت گردش موجودی با نوع آن هم‌خوانی ندارد.';
  END IF;
  IF NEW.movement_type = 'adjustment' AND NEW.quantity_delta = 0 THEN
    RAISE EXCEPTION 'مقدار اصلاح موجودی نمی‌تواند صفر باشد.';
  END IF;

  SELECT COALESCE(sum(movement.quantity_delta), 0)
  INTO v_stock
  FROM public.inventory_stock_movements AS movement
  WHERE movement.organization_id = NEW.organization_id
    AND movement.inventory_id = NEW.inventory_id
    AND movement.warehouse_id = NEW.warehouse_id;

  IF NEW.quantity_delta < 0 THEN
    IF NEW.movement_type = 'rental_issue' AND NEW.reservation_id IS NULL THEN
      RAISE EXCEPTION 'تحویل اجاره باید به رزرو مربوط متصل باشد.';
    END IF;
    IF NEW.reservation_id IS NOT NULL THEN
      SELECT reservation.*
      INTO v_reservation
      FROM public.inventory_reservations AS reservation
      WHERE reservation.id = NEW.reservation_id
        AND reservation.organization_id = NEW.organization_id
        AND reservation.inventory_id = NEW.inventory_id
        AND reservation.warehouse_id = NEW.warehouse_id
      FOR UPDATE;
      IF NOT FOUND OR v_reservation.status <> 'reserved'
        OR abs(NEW.quantity_delta) <> v_reservation.quantity
        OR (NEW.movement_type = 'rental_issue' AND v_reservation.reservation_type <> 'rent')
        OR (NEW.movement_type = 'sale_issue' AND v_reservation.reservation_type <> 'sale') THEN
        RAISE EXCEPTION 'رزرو برای خروج این مقدار موجودی معتبر نیست.';
      END IF;
    ELSE
      SELECT COALESCE(sum(reservation.quantity), 0)
      INTO v_reserved
      FROM public.inventory_reservations AS reservation
      WHERE reservation.organization_id = NEW.organization_id
        AND reservation.inventory_id = NEW.inventory_id
        AND reservation.warehouse_id = NEW.warehouse_id
        AND reservation.status = 'reserved';
      IF v_stock + NEW.quantity_delta < v_reserved THEN
        RAISE EXCEPTION 'این خروج موجودی با رزروهای فعال تداخل دارد.';
      END IF;
    END IF;
    IF v_stock + NEW.quantity_delta < 0 THEN
      RAISE EXCEPTION 'موجودی انبار نمی‌تواند منفی شود.';
    END IF;
  ELSIF NEW.movement_type = 'rental_return' THEN
    IF NEW.reservation_id IS NULL THEN
      RAISE EXCEPTION 'عودت اجاره باید به رزرو مربوط متصل باشد.';
    END IF;
    SELECT reservation.*
    INTO v_reservation
    FROM public.inventory_reservations AS reservation
    WHERE reservation.id = NEW.reservation_id
      AND reservation.organization_id = NEW.organization_id
      AND reservation.inventory_id = NEW.inventory_id
      AND reservation.warehouse_id = NEW.warehouse_id
    FOR UPDATE;
    IF NOT FOUND OR v_reservation.status <> 'issued'
      OR v_reservation.reservation_type <> 'rent'
      OR NEW.quantity_delta <> v_reservation.quantity THEN
      RAISE EXCEPTION 'اطلاعات عودت با رزرو اجاره هم‌خوانی ندارد.';
    END IF;
  ELSIF NEW.reservation_id IS NOT NULL THEN
    RAISE EXCEPTION 'اتصال رزرو فقط برای خروج یا عودت مجاز است.';
  END IF;

  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.finish_inventory_stock_movement()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_previous_stock numeric(14, 3);
  v_previous_cost numeric(14, 0);
BEGIN
  IF NEW.reservation_id IS NOT NULL AND NEW.movement_type IN ('sale_issue', 'rental_issue') THEN
    UPDATE public.inventory_reservations
    SET status = CASE WHEN NEW.movement_type = 'sale_issue' THEN 'fulfilled' ELSE 'issued' END
    WHERE id = NEW.reservation_id;
  ELSIF NEW.reservation_id IS NOT NULL AND NEW.movement_type = 'rental_return' THEN
    UPDATE public.inventory_reservations
    SET status = 'returned'
    WHERE id = NEW.reservation_id;
  END IF;

  IF NEW.quantity_delta > 0
    AND NEW.unit_cost IS NOT NULL
    AND NEW.movement_type IN ('opening', 'purchase') THEN
    SELECT COALESCE(sum(movement.quantity_delta), 0) - NEW.quantity_delta
    INTO v_previous_stock
    FROM public.inventory_stock_movements AS movement
    WHERE movement.organization_id = NEW.organization_id
      AND movement.inventory_id = NEW.inventory_id;
    SELECT item.base_cost INTO v_previous_cost
    FROM public.inventory AS item
    WHERE item.id = NEW.inventory_id
      AND item.organization_id = NEW.organization_id;
    UPDATE public.inventory
    SET base_cost = CASE
      WHEN v_previous_stock <= 0 OR COALESCE(v_previous_cost, 0) <= 0 THEN NEW.unit_cost
      ELSE round(
        (v_previous_stock * v_previous_cost + NEW.quantity_delta * NEW.unit_cost)
        / (v_previous_stock + NEW.quantity_delta)
      )
    END
    WHERE id = NEW.inventory_id
      AND organization_id = NEW.organization_id;
  END IF;
  RETURN NEW;
END;
$function$;

