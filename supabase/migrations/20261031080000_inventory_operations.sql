CREATE OR REPLACE FUNCTION public.set_default_inventory_warehouse(
  p_organization_id uuid,
  p_warehouse_id bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF NOT public.is_organization_member(p_organization_id)
    OR NOT public.has_organization_section(p_organization_id, 'inventory') THEN
    RAISE EXCEPTION 'دسترسی انبار برای این فضای کاری لازم است.';
  END IF;

  PERFORM 1 FROM public.organizations
  WHERE id = p_organization_id
  FOR UPDATE;
  PERFORM pg_catalog.set_config('app.allow_default_inventory_warehouse_change', 'true', true);
  UPDATE public.inventory_warehouses
  SET is_default = false
  WHERE organization_id = p_organization_id
    AND is_default;

  UPDATE public.inventory_warehouses
  SET is_default = true
  WHERE organization_id = p_organization_id
    AND id = p_warehouse_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'انبار انتخاب‌شده در این فضای کاری پیدا نشد.';
  END IF;
END;
$function$;

