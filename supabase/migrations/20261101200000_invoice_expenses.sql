CREATE OR REPLACE FUNCTION public.pay_invoice_expense(
  p_expense_id bigint,
  p_account_id bigint,
  p_payment_date date,
  p_offline_sync_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_expense public.invoice_expenses%ROWTYPE;
  v_invoice public.invoices%ROWTYPE;
  v_account public.financial_accounts%ROWTYPE;
  v_transaction public.cash_transactions%ROWTYPE;
  v_balance numeric(14, 0);
  v_description text;
BEGIN
  IF auth.uid() IS NULL OR p_payment_date IS NULL OR p_offline_sync_id IS NULL THEN
    RAISE EXCEPTION 'کاربر واردشده، تاریخ پرداخت و شناسهٔ گردش الزامی هستند.';
  END IF;

  SELECT * INTO v_expense
  FROM public.invoice_expenses
  WHERE id = p_expense_id
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'هزینهٔ فاکتور پیدا نشد.'; END IF;
  IF NOT public.is_organization_member(v_expense.organization_id)
    OR NOT public.has_organization_section(v_expense.organization_id, 'accounting') THEN
    RAISE EXCEPTION 'برای ثبت پرداخت هزینه باید دسترسی حسابداری داشته باشید.';
  END IF;
  IF v_expense.is_paid THEN
    SELECT * INTO v_transaction
    FROM public.cash_transactions
    WHERE id = v_expense.cash_transaction_id;
    RETURN jsonb_build_object('expense', to_jsonb(v_expense), 'transaction', to_jsonb(v_transaction));
  END IF;

  SELECT * INTO v_invoice
  FROM public.invoices
  WHERE id = v_expense.invoice_id;
  SELECT * INTO v_account
  FROM public.financial_accounts
  WHERE id = p_account_id
  FOR UPDATE;
  IF NOT FOUND OR v_account.organization_id <> v_expense.organization_id THEN
    RAISE EXCEPTION 'حساب پرداخت معتبر نیست.';
  END IF;
  IF p_payment_date < v_account.opening_date THEN
    RAISE EXCEPTION 'تاریخ پرداخت نمی‌تواند قبل از تاریخ افتتاح حساب باشد.';
  END IF;

  SELECT v_account.opening_balance
    + COALESCE(SUM(CASE
        WHEN transaction_type = 'income' THEN amount
        WHEN transaction_type IN ('expense', 'transfer') THEN -amount
        ELSE 0
      END), 0)
  INTO v_balance
  FROM public.cash_transactions
  WHERE account_id = p_account_id;
  SELECT v_balance + COALESCE(SUM(amount), 0)
    INTO v_balance
  FROM public.cash_transactions
  WHERE transaction_type = 'transfer' AND transfer_to_account_id = p_account_id;
  IF v_balance < v_expense.amount THEN
    RAISE EXCEPTION 'موجودی حساب برای پرداخت این هزینه کافی نیست.';
  END IF;

  v_description := 'فاکتور رسمی #' || v_invoice.id::text;
  IF length(btrim(v_expense.description)) > 0 THEN
    v_description := v_description || ' - ' || btrim(v_expense.description);
  ELSE
    v_description := v_description || ' - ' || v_expense.category;
  END IF;

  INSERT INTO public.cash_transactions (
    transaction_type, amount, account_id, invoice_id, category, description,
    transaction_date, offline_sync_id
  ) VALUES (
    'expense', v_expense.amount, p_account_id, NULL, v_expense.category, v_description,
    p_payment_date, p_offline_sync_id
  )
  RETURNING * INTO v_transaction;

  UPDATE public.invoice_expenses
  SET is_paid = true,
      payment_date = p_payment_date,
      account_id = p_account_id,
      cash_transaction_id = v_transaction.id
  WHERE id = v_expense.id
  RETURNING * INTO v_expense;

  RETURN jsonb_build_object('expense', to_jsonb(v_expense), 'transaction', to_jsonb(v_transaction));
END;
$$;

REVOKE ALL ON FUNCTION public.pay_invoice_expense(bigint, bigint, date, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.pay_invoice_expense(bigint, bigint, date, uuid) TO authenticated;
