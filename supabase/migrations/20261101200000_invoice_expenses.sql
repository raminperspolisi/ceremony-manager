CREATE TABLE IF NOT EXISTS public.invoice_expenses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id bigint NOT NULL REFERENCES public.invoices(id) ON DELETE CASCADE,
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
  category text NOT NULL CHECK (length(btrim(category)) > 0),
  description text NOT NULL DEFAULT '',
  amount numeric(14, 0) NOT NULL CHECK (amount > 0),
  expense_date date NOT NULL DEFAULT CURRENT_DATE,
  is_paid boolean NOT NULL DEFAULT false,
  payment_date date,
  account_id bigint REFERENCES public.financial_accounts(id) ON DELETE RESTRICT,
  cash_transaction_id bigint UNIQUE REFERENCES public.cash_transactions(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (is_paid AND payment_date IS NOT NULL AND account_id IS NOT NULL AND cash_transaction_id IS NOT NULL)
    OR
    (NOT is_paid AND payment_date IS NULL AND account_id IS NULL AND cash_transaction_id IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS invoice_expenses_invoice_idx
  ON public.invoice_expenses (invoice_id, expense_date DESC, id DESC);
CREATE INDEX IF NOT EXISTS invoice_expenses_organization_idx
  ON public.invoice_expenses (organization_id);

