CREATE OR REPLACE FUNCTION public.set_invoice_expense_organization()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_organization_id uuid;
BEGIN
  SELECT invoice.organization_id
  INTO v_organization_id
  FROM public.invoices AS invoice
  WHERE invoice.id = NEW.invoice_id;

  IF v_organization_id IS NULL THEN
    RAISE EXCEPTION 'فاکتور انتخاب‌شده پیدا نشد.';
  END IF;
  IF NEW.organization_id IS NOT NULL AND NEW.organization_id <> v_organization_id THEN
    RAISE EXCEPTION 'فاکتور و هزینه باید متعلق به یک فضای کاری باشند.';
  END IF;
  NEW.organization_id := v_organization_id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS invoice_expenses_set_organization ON public.invoice_expenses;
CREATE TRIGGER invoice_expenses_set_organization
BEFORE INSERT OR UPDATE OF invoice_id, organization_id
ON public.invoice_expenses
FOR EACH ROW
EXECUTE FUNCTION public.set_invoice_expense_organization();

CREATE OR REPLACE FUNCTION public.invoice_expense_payment_matches(
  p_organization_id uuid,
  p_amount numeric,
  p_category text,
  p_payment_date date,
  p_account_id bigint,
  p_cash_transaction_id bigint
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.cash_transactions AS transaction
    WHERE transaction.id = p_cash_transaction_id
      AND transaction.organization_id = p_organization_id
      AND transaction.transaction_type = 'expense'
      AND transaction.amount = p_amount
      AND transaction.category = p_category
      AND transaction.transaction_date = p_payment_date
      AND transaction.account_id = p_account_id
  );
$$;

REVOKE ALL ON FUNCTION public.invoice_expense_payment_matches(uuid, numeric, text, date, bigint, bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.invoice_expense_payment_matches(uuid, numeric, text, date, bigint, bigint) TO authenticated;

DROP POLICY IF EXISTS invoice_expenses_read ON public.invoice_expenses;
CREATE POLICY invoice_expenses_read ON public.invoice_expenses
FOR SELECT TO authenticated
USING (
  public.is_organization_member(organization_id)
  AND (
    public.has_organization_section(organization_id, 'official')
    OR public.has_organization_section(organization_id, 'accounting')
  )
);

DROP POLICY IF EXISTS invoice_expenses_insert_unpaid ON public.invoice_expenses;
CREATE POLICY invoice_expenses_insert_unpaid ON public.invoice_expenses
FOR INSERT TO authenticated
WITH CHECK (
  (
    (
      NOT is_paid
      AND payment_date IS NULL
      AND account_id IS NULL
      AND cash_transaction_id IS NULL
    )
    OR (
      is_paid
      AND payment_date IS NOT NULL
      AND account_id IS NOT NULL
      AND cash_transaction_id IS NOT NULL
      AND public.invoice_expense_payment_matches(
        organization_id, amount, category, payment_date, account_id, cash_transaction_id
      )
    )
  )
  AND public.is_organization_member(organization_id)
  AND (
    public.has_organization_section(organization_id, 'official')
    OR public.has_organization_section(organization_id, 'accounting')
  )
);

DROP POLICY IF EXISTS invoice_expenses_update_unpaid ON public.invoice_expenses;
CREATE POLICY invoice_expenses_update_unpaid ON public.invoice_expenses
FOR UPDATE TO authenticated
USING (
  NOT is_paid
  AND public.is_organization_member(organization_id)
  AND (
    public.has_organization_section(organization_id, 'official')
    OR public.has_organization_section(organization_id, 'accounting')
  )
)
WITH CHECK (
  NOT is_paid
  AND payment_date IS NULL
  AND account_id IS NULL
  AND cash_transaction_id IS NULL
  AND public.is_organization_member(organization_id)
  AND (
    public.has_organization_section(organization_id, 'official')
    OR public.has_organization_section(organization_id, 'accounting')
  )
);

